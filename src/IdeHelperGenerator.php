<?php

namespace Milwad\LaravelValidateFilament;

use Closure;
use Filament\Forms\Components\Field;
use ReflectionFunction;
use ReflectionIntersectionType;
use ReflectionNamedType;
use ReflectionParameter;
use ReflectionType;
use ReflectionUnionType;

class IdeHelperGenerator
{
    /**
     * Build the contents of an IDE helper file describing every macro as a `@method` annotation on Field.
     */
    public function generate(): string
    {
        $methods = [];

        foreach ((new FieldMacros)->macros() as $name => $macro) {
            $methods[] = '     * '.$this->methodAnnotation($name, $macro);
        }

        $field = '\\'.Field::class;
        $parent = ($parent = get_parent_class(Field::class)) ? ' extends \\'.$parent : '';
        $methods = implode("\n", $methods);

        return <<<PHP
<?php

/* @noinspection ALL */
// @formatter:off
// phpcs:ignoreFile

/**
 * IDE helper for milwad/laravel-validate-filament.
 *
 * Generated by `php artisan laravel-validate-filament:ide-helper`. Do not edit by hand,
 * and do not include it in your application: it exists only to be read by your IDE.
 */

namespace {
    exit('This file should not be included, only analyzed by your IDE.');
}

namespace Filament\Forms\Components {
    /**
{$methods}
     *
     * @see {$field}
     */
    class Field{$parent} {}
}

PHP;
    }

    /**
     * Build one `@method` line for a macro, e.g. `@method $this validIban(array|string|\Closure $countries = [], ...)`.
     */
    protected function methodAnnotation(string $name, Closure $macro): string
    {
        $parameters = array_map(
            fn (ReflectionParameter $parameter) => $this->parameter($parameter),
            (new ReflectionFunction($macro))->getParameters(),
        );

        $rule = '\\Milwad\\LaravelValidate\\Rules\\'.ucfirst($name);

        return sprintf('@method $this %s(%s) Validate with %s.', $name, implode(', ', $parameters), $rule);
    }

    /**
     * Render a parameter as it would appear in a PHP signature.
     */
    protected function parameter(ReflectionParameter $parameter): string
    {
        $code = '$'.$parameter->getName();

        if ($parameter->hasType()) {
            $code = $this->type($parameter->getType()).' '.$code;
        }

        if ($parameter->isDefaultValueAvailable()) {
            $code .= ' = '.$this->value($parameter->getDefaultValue());
        }

        return $code;
    }

    /**
     * Render a reflected type, prefixing class names with a backslash.
     */
    protected function type(ReflectionType $type): string
    {
        if ($type instanceof ReflectionUnionType || $type instanceof ReflectionIntersectionType) {
            $separator = $type instanceof ReflectionUnionType ? '|' : '&';

            return implode($separator, array_map(fn (ReflectionType $type) => $this->type($type), $type->getTypes()));
        }

        /** @var ReflectionNamedType $type */
        $name = $type->isBuiltin() ? $type->getName() : '\\'.$type->getName();

        return $type->allowsNull() && $name !== 'null' && $name !== 'mixed' ? '?'.$name : $name;
    }

    /**
     * Render a default value as PHP code.
     */
    protected function value(mixed $value): string
    {
        return match (true) {
            $value === null => 'null',
            is_bool($value) => $value ? 'true' : 'false',
            $value === [] => '[]',
            is_array($value) => '['.implode(', ', array_map(fn ($item) => $this->value($item), $value)).']',
            default => var_export($value, true),
        };
    }
}
